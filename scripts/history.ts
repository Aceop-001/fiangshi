/**
 * Build history from git, for the test report: per commit, the test files, the test cases declared in source
 * (`it(` occurrences; a table-driven `it.each` counts once, so this is below the number vitest runs), and the
 * accept gates (`gate("G<n>` in scripts/accept.ts). Reads only the local repository.
 *
 *   npx tsx scripts/history.ts            print the table
 *   npx tsx scripts/history.ts --write    write artifacts/history.md
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../src/config.js";

const git = (...a: string[]) => execFileSync("git", a, { cwd: ROOT, encoding: "utf8", maxBuffer: 64 << 20, stdio: ["ignore", "pipe", "ignore"] });

export type Row = { hash: string; date: string; subject: string; test_files: number; test_cases: number; gates: number };

export function history(): Row[] {
  const log = git("log", "--reverse", "--format=%h%x09%ad%x09%s", "--date=short").trim().split("\n");
  return log.map((l) => {
    const [hash, date, subject] = l.split("\t") as [string, string, string];
    const files = git("ls-tree", "-r", "--name-only", hash, "--", "tests").split("\n").filter((f) => f.endsWith(".test.ts"));
    let cases = 0;
    try {
      for (const line of git("grep", "-cE", "\\bit\\(", hash, "--", "tests").trim().split("\n")) if (line) cases += Number(line.split(":").pop());
    } catch {
      /* git grep exits 1 when nothing matches */
    }
    let gates = 0;
    try {
      gates = new Set([...git("show", `${hash}:scripts/accept.ts`).matchAll(/gate\("(G\d+)/g)].map((m) => m[1])).size;
    } catch {
      /* no accept script yet */
    }
    return { hash, date, subject, test_files: files.length, test_cases: cases, gates };
  });
}

export function historyMd(rows: Row[]): string {
  const out = [
    "# Build history",
    "",
    "Generated by `npx tsx scripts/history.ts --write` from the local git history. One row per commit.",
    "Test cases are `it(` calls in `tests/` (a table-driven case counts once, so vitest runs more). Gates are the distinct `G<n>` checks in `scripts/accept.ts`.",
    "",
    "| commit | date | test files | test cases | gates | subject |",
    "|---|---|---|---|---|---|",
  ];
  for (const r of rows) out.push(`| \`${r.hash}\` | ${r.date} | ${r.test_files} | ${r.test_cases} | ${r.gates} | ${r.subject.replace(/\|/g, "\\|")} |`);
  return out.join("\n") + "\n";
}

if (process.argv[1]?.endsWith("history.ts")) {
  const md = historyMd(history());
  if (process.argv.includes("--write")) writeFileSync(join(ROOT, "artifacts", "history.md"), md);
  process.stdout.write(md);
}
