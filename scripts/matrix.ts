/**
 * Render artifacts/lab.md (and artifacts/matrix.md, same content) from the latest fixtures/lab/results*.json.
 * Reports what happened: a case that did not trip its intended vow is a FAILURE. 0 credits.
 * Usage: npx tsx scripts/matrix.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const LAB = join(ROOT, "fixtures", "lab");
const files = readdirSync(LAB).filter((f) => /^results(-attempt\d+)?\.json$/.test(f)).sort((a, b) => a.length - b.length || a.localeCompare(b));
const latest = files[files.length - 1]!;
const run = JSON.parse(readFileSync(join(LAB, latest), "utf8")) as { ran_at: string; serv_model: string; census_at: string; results: Record<string, any>[] };
const R = run.results;

const L: string[] = [];
L.push(`# Adversarial lab`, ``);
L.push(`Generated by \`npx tsx scripts/matrix.ts\` from \`fixtures/lab/${latest}\` (run ${run.ran_at}). The cases and their expected verdicts are in \`fixtures/lab/cases.json\`, committed **before** the run and not edited since. Pipeline: live unpaid probe → V6 gate → signals (cached 90-day census row; B1 one live query; B3 synthetic) → SERV (${run.serv_model}) ∥ Dolphin → vows → sealed receipt.`, ``);
L.push(`| case | archetype | construction | expected | actual | vow fired | cost | outcome |`, `|---|---|---|---|---|---|---|---|`);
for (const r of R) {
  const a = r.actual;
  const cost = `$${Number(r.cost_usd).toFixed(5)}${r.surf_credits ? ` (${r.surf_credits} Surf credits)` : ""}`;
  L.push(`| ${r.id} | ${r.archetype} | ${String(r.construction).replace(/\|/g, "/")} | ${r.expected_band} · ${r.expected_vow ?? "no vow"} | ${a.band}${a.score !== undefined ? ` (${a.score})` : ""}${a.degraded ? " · degraded" : ""} | ${(a.vows_fired ?? []).join(", ") || "none"} | ${cost} | **${r.outcome}**${r.why ? `: ${r.why}` : ""} |`);
}

// per-vow precision / recall against the written expectations
const vows = ["null_payee", "age", "kinship", "history", "identity", "silence"];
L.push(``, `## Per-vow precision and recall (against the written expectations)`, ``);
L.push(`| vow | expected in | fired in | TP | FP | FN | precision | recall |`, `|---|---|---|---|---|---|---|---|`);
for (const v of vows) {
  const exp = R.filter((r) => r.expected_vow === v).map((r) => r.id);
  const fired = R.filter((r) => (r.actual.vows_fired ?? []).includes(v)).map((r) => r.id);
  const tp = exp.filter((id) => fired.includes(id)).length;
  const fp = fired.filter((id) => !exp.includes(id)).length;
  const fn = exp.length - tp;
  const p = tp + fp ? (tp / (tp + fp)).toFixed(2) : "n/a";
  const rc = tp + fn ? (tp / (tp + fn)).toFixed(2) : "n/a";
  L.push(`| ${v} | ${exp.join(", ") || "-"} | ${fired.join(", ") || "-"} | ${tp} | ${fp} | ${fn} | ${p} | ${rc} |`);
}
const controls = R.filter((r) => r.archetype === "control");
const ctrlAllow = controls.filter((r) => r.actual.band === "ALLOW").length;
const dolTimeouts = R.filter((r) => String(r.actual?.dolphin?.error ?? "").includes("timeout")).length;
const pass = R.filter((r) => r.outcome === "PASS").length;
L.push(``, `Controls: **${ctrlAllow} of ${controls.length} ALLOW**. A control that is not ALLOW is a false positive for the product (an honest seller held back).`, ``);

L.push(`## What this means`, ``);
L.push(
  `${pass} of ${R.length} cases matched their written expectation. **The vows that can be exercised on live data did their job:** the sybil-funded payee was BLOCKed by kinship, the zero-address endpoint was BLOCKed by V6 at probe time for $0.00 with no data or model call, and the payee with no on-chain history went to REVIEW through silence. ` +
    `**Three expectations could not be met honestly,** and the lab says so rather than bending the cases. A brand-new wallet that has never been funded has no age to judge, so it lands on silence (REVIEW), not age (BLOCK); Fiangshi cannot fund a wallet to manufacture one. No live payee in the 800-payee census was a dormant-then-reactivated "sleeper", and the history vow only fires on zero payers above $0.50, so the synthetic sleeper was scored by the rubric instead (BLOCK). The identity vow only fires on claimants younger than 7 days, so an older uncorroborated claimant gets REVIEW from its score, not from the vow. ` +
    `**All ${controls.length} real ALLOW controls came back REVIEW** because the Dolphin identity extractor timed out on ${dolTimeouts} of ${R.length} cases (8 s per attempt, one retry). By design a failed extractor caps the verdict at REVIEW, so a slow provider costs an honest seller its ALLOW but can never produce a false ALLOW. Two of the three controls had a deterministic score in the ALLOW range and SERV advising ALLOW, so the only thing standing between them and ALLOW was the extractor timeout.`,
  ``,
);
const md = L.join("\n") + "\n";
writeFileSync(join(ROOT, "artifacts", "lab.md"), md);
writeFileSync(join(ROOT, "artifacts", "matrix.md"), md);
console.log(md);
