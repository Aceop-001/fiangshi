/**
 * Unit economics from MEASURED inputs (no invented numbers). Usage: npx tsx scripts/pricing.ts [--write]
 *  - Surf credit price: $0.006 list (agents.asksurf.ai/docs/pricing, 2026-11-08).
 *  - Surf SQL per call: balance delta 4 credits (keyed sync, 2026-11-09 census chunks); meta.credits_used reports 5.
 *  - Labels per call: 1 measured, 4 documented.
 *  - SERV / Dolphin per call: tokens from fixtures/models/*.json × documented per-1M prices.
 *  - Census amortisation: credits actually spent on the census (gate + stages + refusals) / payees with rows.
 * --write appends the tables to artifacts/costs.md under "Pricing v2".
 */
import { appendFileSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const CREDIT = 0.006;
const PRICE = { cold: 0.15, cached: 0.05 };
const SERV_PER_M = { in: 1.0, out: 6.0 }; // gpt-5.4-mini, docs.openserv.ai/serv-reasoning/models
const DOLPHIN_PER_M = { in: 0.01, out: 0.07 }; // DeepSeek V4.1 Flash, dphn.ai/docs/dphn-api

interface Call { prompt_tokens: number | null; completion_tokens: number | null }
const modelCost = (prefix: string, p: { in: number; out: number }) => {
  const files = readdirSync(join(ROOT, "fixtures", "models")).filter((f) => f.startsWith(prefix));
  const costs = files.flatMap((f) =>
    ((JSON.parse(readFileSync(join(ROOT, "fixtures", "models", f), "utf8")) as { calls: Call[] }).calls ?? [])
      .filter((c) => c.prompt_tokens !== null && c.completion_tokens !== null)
      .map((c) => (c.prompt_tokens! * p.in + c.completion_tokens! * p.out) / 1e6),
  );
  return { mean: costs.reduce((a, b) => a + b, 0) / Math.max(1, costs.length), n: costs.length };
};
const serv = modelCost("serv-", SERV_PER_M);
const dolphin = modelCost("dolphin-", DOLPHIN_PER_M);
const models = serv.mean + dolphin.mean;

// census spend, from the checkpoint + known extra calls on 2026-11-09 (gate 4, failed async stage 4, preflight 4, refusal 4)
const cp = JSON.parse(readFileSync(join(ROOT, "fixtures", "audit", "checkpoint-sample-census.json"), "utf8")) as { chunk_costs?: { payees: number; credits: number | null }[]; outbound_done?: string[] };
const chunkCredits = (cp.chunk_costs ?? []).reduce((a, c) => a + (c.credits ?? 0), 0);
const chunkPayees = (cp.chunk_costs ?? []).reduce((a, c) => a + c.payees, 0);
const overhead = 16;
const audited = cp.outbound_done?.length ?? 0;

const fmt = (x: number, d = 4) => `$${x.toFixed(d)}`;
const cold = (sqlCredits: number, labelCredits: number) => 3 * sqlCredits * CREDIT + labelCredits * CREDIT + models; // payee in + out + funder out + labels
const L: string[] = [];
L.push(`## Pricing v2 (generated by \`npx tsx scripts/pricing.ts\`)`, ``);
L.push(`Inputs: Surf $${CREDIT}/credit · SQL 4 credits/call (balance delta; meta reports 5) · labels 1 measured / 4 documented · SERV ${fmt(serv.mean, 5)}/call (n=${serv.n}) · Dolphin ${fmt(dolphin.mean, 6)}/call (n=${dolphin.n}).`, ``);
L.push(`| check type | what runs | cost | price | margin |`, `|---|---|---|---|---|`);
const c4 = cold(4, 1);
const c5 = cold(5, 4);
L.push(`| cold, measured (1 payee, 3 SQL × 4 + labels 1) | Surf ×4 calls + SERV + Dolphin | ${fmt(c4)} | ${fmt(PRICE.cold, 2)} | ${fmt(PRICE.cold - c4)} (${((1 - c4 / PRICE.cold) * 100).toFixed(0)}%) |`);
L.push(`| cold, conservative (3 SQL × 5 as meta reports + labels 4 documented) | same | ${fmt(c5)} | ${fmt(PRICE.cold, 2)} | ${fmt(PRICE.cold - c5)} (${((1 - c5 / PRICE.cold) * 100).toFixed(0)}%) |`);
L.push(`| cached (snapshot hit) | SERV + Dolphin only | ${fmt(models)} | ${fmt(PRICE.cached, 2)} | ${fmt(PRICE.cached - models)} (${((1 - models / PRICE.cached) * 100).toFixed(0)}%) |`, ``);
L.push(`### Shrink table — Surf cost per payee as batch size grows (per-call billing)`, ``);
L.push(`| batch size | Surf credits / payee (3 SQL × 4 + labels 1 per 100 addr) | Surf $ / payee | + models | total / check |`, `|---|---|---|---|---|`);
for (const b of [1, 10, 50, 300]) {
  const credits = (3 * 4) / b + (Math.ceil((2 * b) / 100) * 1) / b; // 3 SQL calls (payee in, payee out, funder out) shared by b payees + label calls (≈2 addresses/payee)
  const usd = credits * CREDIT;
  L.push(`| ${b} | ${credits.toFixed(3)} | ${fmt(usd, 5)} | ${fmt(models, 5)} | ${fmt(usd + models, 5)} |`);
}
L.push(``, `### Census amortisation (actual, 2026-11-09)`, ``);
L.push(`| | credits | payees | $ / payee |`, `|---|---|---|---|`);
L.push(`| chunk calls only | ${chunkCredits} | ${chunkPayees} | ${fmt((chunkCredits * CREDIT) / Math.max(1, chunkPayees), 5)} |`);
L.push(`| including gate, failed async stage, preflight, billed refusal (+${overhead}) | ${chunkCredits + overhead} | ${audited} | ${fmt(((chunkCredits + overhead) * CREDIT) / Math.max(1, audited), 5)} |`);
L.push(`| planning estimate (190 credits / 1,923 payees) | 190 | 1923 | ${fmt((190 * CREDIT) / 1923, 5)} |`, ``);
const md = L.join("\n") + "\n";
console.log(md);
if (process.argv.includes("--write")) appendFileSync(join(ROOT, "artifacts", "costs.md"), "\n" + md);
