/**
 * Render artifacts/lab.md (and artifacts/matrix.md, same content) from the lab results (0 credits).
 * Latest run = the newest fixtures/lab/results*.json. The first run (results.json, cases.json) stays visible as history:
 * its failures were real under the rules of that day.
 * Usage: npx tsx scripts/matrix.ts
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const LAB = join(ROOT, "fixtures", "lab");
type Run = { ran_at: string; cases_file?: string; serv_model: string; census_at: string; results: Record<string, any>[] };
const files = readdirSync(LAB).filter((f) => /^results(-attempt\d+)?\.json$/.test(f)).sort((a, b) => a.length - b.length || a.localeCompare(b));
const load = (f: string) => JSON.parse(readFileSync(join(LAB, f), "utf8")) as Run;
const latestFile = files[files.length - 1]!;
const run = load(latestFile);
const first = load(files[0]!);
const R = run.results;
const VOWS = ["null_payee", "age", "kinship", "history", "identity", "silence"];

const L: string[] = [];
L.push(`# Adversarial lab`, ``);
L.push(`Generated by \`npx tsx scripts/matrix.ts\` from \`fixtures/lab/${latestFile}\` (run ${run.ran_at}, cases \`fixtures/lab/${run.cases_file ?? "cases.json"}\`). Expectations were committed **before** each run and never edited afterwards. Pipeline: live unpaid probe → V6 gate → signals (cached 90-day census row; B1 = a never-funded random address; B3 = synthetic) → SERV (${run.serv_model}) ∥ Dolphin (optional enrichment, 12 s + one retry) → vows → sealed receipt.`, ``);
L.push(`| case | archetype | expected | actual | vow fired | enrichment | cost | outcome |`, `|---|---|---|---|---|---|---|---|`);
for (const r of R) {
  const a = r.actual;
  const enr = a.enrichment ? `${a.enrichment.status}${a.enrichment.reason ? ` (${String(a.enrichment.reason).replace(/\|/g, "/")})` : ""}` : "n/a (gated before models)";
  const cost = `$${Number(r.cost_usd).toFixed(5)}${r.surf_credits ? ` + ${r.surf_credits} Surf credits` : ""}`;
  const exp = `${r.expected_band} · ${r.expected_vow ?? "no vow"}${r.alternate_path ? " *(alternate path)*" : ""}`;
  L.push(`| ${r.id} | ${r.archetype} | ${exp} | ${a.band}${a.score !== undefined ? ` (${a.score})` : ""} | ${(a.vows_fired ?? []).join(", ") || "none"} | ${enr} | ${cost} | **${r.outcome}**${r.why ? `: ${r.why}` : ""} |`);
}
L.push(``, `Construction of each case: \`fixtures/lab/${run.cases_file ?? "cases.json"}\`. Alternate paths are explained there (\`expectation_change\`).`, ``);

L.push(`## Per-vow precision and recall (this run, against its written expectations)`, ``);
const pr: string[] = [];
for (const v of VOWS) {
  const exp = R.filter((r) => r.expected_vow === v).map((r) => r.id);
  const fired = R.filter((r) => (r.actual.vows_fired ?? []).includes(v)).map((r) => r.id);
  const tp = exp.filter((id) => fired.includes(id)).length;
  const fp = fired.filter((id) => !exp.includes(id));
  const fn = exp.length - tp;
  const p = tp + fp.length ? (tp / (tp + fp.length)).toFixed(2) : "n/a";
  const rc = tp + fn ? (tp / (tp + fn)).toFixed(2) : "n/a";
  pr.push(`**${v}** P ${p} / R ${rc}${fp.length ? ` (also fired on ${fp.join(", ")})` : ""}`);
}
L.push(pr.join(" · "), ``);
const extra = R.filter((r) => (r.actual.vows_fired ?? []).some((v: string) => v !== r.expected_vow));
for (const r of extra) L.push(`- ${r.id}: also fired ${(r.actual.vows_fired as string[]).filter((v) => v !== r.expected_vow).join(", ")} (${(r.actual.vow_reasons ?? []).filter((x: string) => !x.startsWith(r.expected_vow ?? "-")).join("; ")}). This is correct under the current rules: the band is unchanged and the expected vow also fired.`);
if (extra.length) L.push(``);

const controls = R.filter((r) => r.archetype === "control");
const pass = R.filter((r) => r.outcome === "PASS").length;
const dolTimeouts = R.filter((r) => String(r.actual?.enrichment?.reason ?? "").includes("timeout")).length;
L.push(`## What this means`, ``);
L.push(
  `${pass} of ${R.length} cases matched their written expectation. **${controls.filter((r) => r.actual.band === "ALLOW").length} of ${controls.length} real controls reached ALLOW** with no vow, even though the Dolphin identity extractor timed out on ${dolTimeouts} of ${R.length} cases. Identity extraction is optional enrichment: a timeout is stamped on the receipt (\`enrichment: incomplete\`) and never caps the verdict. Missing **Surf** data still routes to silence (REVIEW), so a missing required signal never quietly becomes ALLOW. ` +
    `The sybil-funded payee was BLOCKed by kinship, and the zero-address endpoint was BLOCKed by V6 at probe time for $0.00 with no model call. ${(() => {
      const b4 = R.find((r) => r.archetype === "anon-claimant");
      if (!b4) return "";
      const v = (b4.actual.vows_fired ?? []) as string[];
      return v.includes("identity")
        ? `The uncorroborated claimant was held at ${b4.actual.band} by V5. `
        : `The uncorroborated claimant landed on ${b4.actual.band} (score ${b4.actual.score}) with **no identity vow**: under identity neutrality (2026-11-09) an uncorroborated claim is treated exactly like no claim, so V5 fires only on a contradicted claim. Its expectation (REVIEW · identity) was written before that rule change and is left unedited, so it shows as a FAILURE. `;
    })()}The payee with no on-chain history went to REVIEW through silence. ` +
    `Two archetypes cannot be reached the way the original lab assumed, and the cases say so. A never-funded wallet has no age to judge, so it lands on silence, not age; Fiangshi holds no funds and cannot fund one. No live sleeper exists in the 800-payee census, and the synthetic one has payers, so the history vow cannot fire on it; it reaches REVIEW by score.`,
  ``,
);

const prevFile = files.length >= 2 ? files[files.length - 2]! : null;
if (prevFile && prevFile !== files[0]) {
  const prev = load(prevFile);
  L.push(`## Previous run (${prev.ran_at}, \`fixtures/lab/${prevFile}\`, rules before identity neutrality)`, ``);
  L.push(`| case | actual then | actual now |`, `|---|---|---|`);
  for (const r of prev.results) {
    const now = R.find((x) => x.id === r.id);
    L.push(`| ${r.id} | ${r.actual.band} · ${(r.actual.vows_fired ?? []).join(", ") || "none"} · ${r.outcome} | ${now ? `${now.actual.band} · ${(now.actual.vows_fired ?? []).join(", ") || "none"} · ${now.outcome}` : "n/a"} |`);
  }
  L.push(``);
}

L.push(`## History: first run (${first.ran_at}, \`fixtures/lab/${files[0]}\`, rules of that day)`, ``);
L.push(`| case | expected | actual | outcome |`, `|---|---|---|---|`);
for (const r of first.results) L.push(`| ${r.id} | ${r.expected_band} · ${r.expected_vow ?? "no vow"} | ${r.actual.band} · ${(r.actual.vows_fired ?? []).join(", ") || "none"} | ${r.outcome}${r.why ? `: ${r.why}` : ""} |`);
L.push(``, `Those failures were real under the rules of that day. B1 and B3 could not reach their intended vows, and are now expected on their alternate paths, with the reason written into \`cases-v2.json\` before the re-run. V5 then fired only on uncorroborated claims under 7 days old; it now fires only on a contradicted claim (identity neutrality). The controls were capped at REVIEW by a failed optional extractor, which now stamps \`enrichment: incomplete\` instead.`, ``);
const md = L.join("\n") + "\n";
writeFileSync(join(ROOT, "artifacts", "lab.md"), md);
writeFileSync(join(ROOT, "artifacts", "matrix.md"), md);
console.log(md.split("\n").slice(0, 16).join("\n"));
