/**
 * The census refresh report (0 credits): artifacts/refresh.md, from committed fixtures only.
 *   npx tsx scripts/refresh-report.ts
 * Describes the refresh being served (20 Nov: sample-census-r4): credits by balance, coverage, the bands as issued and
 * as served, band movement against the baseline snapshot of the previous census (artifacts/index-2026-11-17.json, the
 * live /v1/index.json taken just before the run), and the kinship sensitivity. Earlier reports are kept, dated:
 * artifacts/refresh-2026-11-17.md and artifacts/refresh-2026-11-13.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../src/config.js";
import type { Band } from "../src/core/types.js";
import { pinReferenceTime } from "../src/reference-time.js";

/** table column order */
const BANDS: Band[] = ["ALLOW", "REVIEW", "BLOCK"];

const reference = pinReferenceTime();
const { loadCensus } = await import("../src/census.js");
const { sensitivity } = await import("./sensitivity.js");

const bal = JSON.parse(readFileSync(join(ROOT, "fixtures", "audit", "balances.json"), "utf8")).refresh_r4;
const base = JSON.parse(readFileSync(join(ROOT, "artifacts", "index-2026-11-17.json"), "utf8")) as { census_at: string; payees: { payee: string; url: string; issued_band: Band }[] };
const c = loadCensus();
const baseBy = new Map(base.payees.map((p) => [p.payee, p]));
const overlap = c.payees.filter((p) => baseBy.has(p.payee));
const moves = new Map<string, number>();
for (const p of overlap) {
  const o = baseBy.get(p.payee)!.issued_band;
  if (o !== p.issued_band) moves.set(`${o} → ${p.issued_band}`, (moves.get(`${o} → ${p.issued_band}`) ?? 0) + 1);
}
const wasAllow = base.payees.filter((p) => p.issued_band === "ALLOW");
const keptAllow = wasAllow.filter((p) => c.payees.find((x) => x.payee === p.payee)?.issued_band === "ALLOW");
const baseBands = Object.fromEntries(BANDS.map((b) => [b, base.payees.filter((p) => p.issued_band === b).length])) as Record<Band, number>;

const at = (iso: string) => {
  process.env.FIANGSHI_NOW = iso;
  const v = loadCensus();
  return { bands: v.bands, stale: v.payees_stale, capped: v.payees.filter((p) => p.band_cap).length };
};
const now = at(reference);
const past = at(new Date(Date.parse(c.newest_as_of) + (c.stale_limit_hours + 0.1) * 3_600_000).toISOString());
process.env.FIANGSHI_NOW = reference;
const s = sensitivity();
const row = (b: Record<Band, number>) => BANDS.map((x) => b[x].toLocaleString("en-US")).join(" | ");
const day = new Date(c.at).toISOString().slice(0, 10);

const L = [
  `# Census refresh, ${day}`,
  ``,
  `Generated by \`npx tsx scripts/refresh-report.ts\` from committed fixtures (0 credits). Reference time ${reference}. The previous refresh is described in [refresh-2026-11-17.md](refresh-2026-11-17.md).`,
  ``,
  `## Credits (account balance, the billed source of truth)`,
  ``,
  `| reading | balance |`,
  `|---|---|`,
  `| start (preflight, \`surf me-credits\`) | ${bal.start} |`,
  `| after the paid gate and the payee pass (${bal.payee_sql_calls} SQL calls, ${bal.billed_refusals} refusals) | ${bal.after_payees} |`,
  `| after labels (${bal.label_calls} calls, every new funder labelled) | ${bal.after_labels} |`,
  ``,
  `Spent **${bal.start - bal.after_labels} credits** against a cap of ${bal.cap} (floor ${bal.floor}). Labels already bought on 13 and 17 Nov were reused (seeded from the previous checkpoint), so only new addresses were paid for.`,
  ``,
  `## Coverage`,
  ``,
  `Re-collected ${bal.payees_collected.toLocaleString("en-US")} payees out of the catalog's ${c.catalog_payees.toLocaleString("en-US")}, each with its own \`as_of\` (newest ${c.newest_as_of}). The remaining payee is the zero address, blocked by the null-payee rule before any data call and carried over.`,
  ``,
  `## Bands`,
  ``,
  `| census | payees | ALLOW | REVIEW | BLOCK |`,
  `|---|---|---|---|---|`,
  `| previous refresh, as issued (baseline snapshot, census ${base.census_at.slice(0, 16)}Z) | ${base.payees.length.toLocaleString("en-US")} | ${row(baseBands)} |`,
  `| this refresh, as issued | ${c.payees.length.toLocaleString("en-US")} | ${row(c.issued_bands)} |`,
  `| this refresh, served at the reference time | ${c.payees.length.toLocaleString("en-US")} | ${row(now.bands)} |`,
  `| this refresh, served once the newest record is past ${c.stale_limit_hours} h | ${c.payees.length.toLocaleString("en-US")} | ${row(past.bands)} |`,
  ``,
  `**ALLOWs moved by the stale cap:** ${c.issued_bands.ALLOW - now.bands.ALLOW} at the reference time (${now.stale} stale record, ${now.capped} capped). Once every record is past the limit, all ${c.issued_bands.ALLOW} ALLOWs serve as REVIEW until the next refresh.`,
  ``,
  `## Movement against the baseline (${overlap.length} payees in both)`,
  ``,
  `| issued band, previous → this refresh | payees |`,
  `|---|---|`,
  ...[...moves.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} |`),
  `| unchanged | ${overlap.length - [...moves.values()].reduce((a, b) => a + b, 0)} |`,
  ``,
  `Of the ${wasAllow.length} payees issued ALLOW in the baseline, **${keptAllow.length}** are ALLOW again and ${wasAllow.length - keptAllow.length} are not. Why bands move: the 90-day window moved, so for a wallet older than the window a different first sender can stand in for its funder, and the kinship rule follows that sender.`,
  ``,
  `## Kinship sensitivity (artifacts/sensitivity.md)`,
  ``,
  `| policy | ALLOW | REVIEW | BLOCK |`,
  `|---|---|---|---|`,
  ...(["A", "B", "C"] as const).map((p) => `| ${p}${p === "B" ? " (applied)" : ""} | ${row(s.policies[p])} |`),
  ``,
  `Upper bound on false blocks: at most ${s.policies.B.BLOCK - s.policies.C.BLOCK} of the ${s.policies.B.BLOCK} BLOCKs (${((100 * (s.policies.B.BLOCK - s.policies.C.BLOCK)) / s.policies.B.BLOCK).toFixed(0)}%) depend on unnamed shared funders being something other than exchanges.`,
  ``,
];
writeFileSync(join(ROOT, "artifacts", "refresh.md"), L.join("\n"));
console.log(`wrote artifacts/refresh.md (${day})`);
