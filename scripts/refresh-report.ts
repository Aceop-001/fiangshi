/**
 * The census refresh report (0 credits): artifacts/refresh.md, from committed fixtures only.
 *   npx tsx scripts/refresh-report.ts
 * Credits (balance readings), coverage, band movement between the 9 Nov census (policy v4) and the 13 Nov refresh,
 * what the stale cap does at the reference time and after the limit, and why bands moved (first funder drift).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "../src/config.js";
import type { Band } from "../src/core/types.js";

/** table column order */
const BANDS: Band[] = ["ALLOW", "REVIEW", "BLOCK"];
import { pinReferenceTime } from "../src/reference-time.js";

const reference = pinReferenceTime();
const { legacyCensus, loadCensus } = await import("../src/census.js");
const { sensitivity } = await import("./sensitivity.js");

const bal = JSON.parse(readFileSync(join(ROOT, "fixtures", "audit", "balances.json"), "utf8")).refresh;
const c = loadCensus();
const old = legacyCensus();
const oldBy = new Map(old.payees.map((p) => [p.payee, p]));
const oldSig = new Map(old.set.signals.map((s) => [s.payee, s]));
const count = (ps: { issued_band: Band }[]) => Object.fromEntries(BANDS.map((b) => [b, ps.filter((p) => p.issued_band === b).length])) as Record<Band, number>;

const overlap = c.payees.filter((p) => oldBy.has(p.payee));
const moves = new Map<string, number>();
for (const p of overlap) {
  const o = oldBy.get(p.payee)!.issued_band;
  if (o !== p.issued_band) moves.set(`${o} → ${p.issued_band}`, (moves.get(`${o} → ${p.issued_band}`) ?? 0) + 1);
}
let funderChanged = 0;
let kinNew = 0;
let kinNewSameFunder = 0;
for (const p of overlap) {
  const a = oldSig.get(p.payee)?.first_funder ?? null;
  const b = c.signals.get(p.payee)?.first_funder ?? null;
  if (a !== b) funderChanged++;
  if (!oldBy.get(p.payee)!.vows.includes("kinship") && p.vows.includes("kinship")) {
    kinNew++;
    if (a === b) kinNewSameFunder++;
  }
}
// the stale cap at the reference time, and just past the limit for the newest record
const at = (iso: string) => {
  process.env.FIANGSHI_NOW = iso;
  const v = loadCensus();
  return { bands: v.bands, stale: v.payees_stale, capped: v.payees.filter((p) => p.band_cap).length };
};
const now = at(reference);
const past = at(new Date(Date.parse(c.newest_as_of) + (c.stale_limit_hours + 0.1) * 3_600_000).toISOString());
process.env.FIANGSHI_NOW = reference;
const s = sensitivity();
const row = (b: Record<Band, number>) => BANDS.map((x) => b[x].toLocaleString("en-US")).join(" | ");

const L = [
  `# Census refresh, 13 Nov 2026`,
  ``,
  `Generated by \`npx tsx scripts/refresh-report.ts\` from committed fixtures (0 credits). Reference time ${reference}.`,
  ``,
  `## Credits (account balance, the billed source of truth)`,
  ``,
  `| reading | balance |`,
  `|---|---|`,
  `| start (preflight, \`surf me-credits\`) | ${bal.start} |`,
  `| after the paid gate | ${bal.after_gate} |`,
  `| after the payee pass (${bal.payee_sql_calls} SQL calls, ${bal.billed_refusals} refusals) | ${bal.after_payees} |`,
  `| after labels (${bal.label_calls} calls of 19, stopped at the floor) | ${bal.after_labels} |`,
  ``,
  `Spent **${bal.start - bal.after_labels} credits** against a cap of ${bal.cap} (floor ${bal.floor}). Payee SQL cost ${((bal.after_gate - bal.after_payees) / bal.payees_collected).toFixed(3)} credits per payee; the guard stops above 0.40. ${bal.labels_reused} labelled addresses were reused from 9 Nov and ${bal.labels_new} were bought, shared funders first.`,
  ``,
  `## Coverage`,
  ``,
  `${bal.payees_collected.toLocaleString("en-US")} of ${c.catalog_payees.toLocaleString("en-US")} Base payees re-collected, each with its own \`as_of\` (${c.payees.filter((p) => p.as_of >= "2026-11-13").map((p) => p.as_of).sort()[0]} to ${c.newest_as_of}). ${bal.v6_blocked_before_any_call} payee, the zero address, was blocked by V6 before any call; its 9 Nov record is kept with its own old \`as_of\`, so it is stale (it is a BLOCK, which the cap never changes). Records are united by payee: none was dropped.`,
  ``,
  `## Bands`,
  ``,
  `| census | payees | ALLOW | REVIEW | BLOCK |`,
  `|---|---|---|---|---|`,
  `| 9 Nov, policy 2026-11-09.4 | ${old.payees.length} | ${row(count(old.payees))} |`,
  `| 13 Nov, policy 2026-11-13.5, as issued | ${c.payees.length.toLocaleString("en-US")} | ${row(c.issued_bands)} |`,
  `| 13 Nov, served at the reference time | ${c.payees.length.toLocaleString("en-US")} | ${row(now.bands)} |`,
  `| 13 Nov, served once the newest record is past ${c.stale_limit_hours} h | ${c.payees.length.toLocaleString("en-US")} | ${row(past.bands)} |`,
  ``,
  `**ALLOWs moved by the stale cap:** ${c.issued_bands.ALLOW - now.bands.ALLOW} at the reference time (${now.stale} stale record, ${now.capped} capped). Once every record is past the limit, all ${c.issued_bands.ALLOW} ALLOWs serve as REVIEW until the next refresh; BLOCKs never move.`,
  ``,
  `## Movement among the ${overlap.length} payees in both censuses`,
  ``,
  `| issued band, 9 Nov → 13 Nov | payees |`,
  `|---|---|`,
  ...[...moves.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} |`),
  `| unchanged | ${overlap.length - [...moves.values()].reduce((a, b) => a + b, 0)} |`,
  ``,
  `Why: the 90-day window moved four days. For a wallet older than the window, the first sender inside it stands in for its funder; that sender changed for **${funderChanged} of ${overlap.length}** payees. Kinship newly fired on ${kinNew}: ${kinNewSameFunder} because the full catalog put more payees on the same funder, ${kinNew - kinNewSameFunder} because the first sender changed. No rule, weight or threshold changed.`,
  ``,
  `## Kinship sensitivity (artifacts/sensitivity.md)`,
  ``,
  `| policy | ALLOW | REVIEW | BLOCK |`,
  `|---|---|---|---|`,
  ...(["A", "B", "C"] as const).map((p) => `| ${p}${p === "B" ? " (applied)" : ""} | ${row(s.policies[p])} |`),
  ``,
  `Upper bound on false blocks: at most ${s.policies.B.BLOCK - s.policies.C.BLOCK} of the ${s.policies.B.BLOCK} BLOCKs (${((100 * (s.policies.B.BLOCK - s.policies.C.BLOCK)) / s.policies.B.BLOCK).toFixed(0)}%) depend on unnamed shared funders not being exchanges.`,
  ``,
];
writeFileSync(join(ROOT, "artifacts", "refresh.md"), L.join("\n"));
console.log(L.join("\n"));
