/**
 * Unit economics from MEASURED inputs (no invented numbers). Usage: npx tsx scripts/pricing.ts [--write]
 *  - Surf credit price: $0.006 list (agents.asksurf.ai/docs/pricing, 2026-11-08).
 *  - Per-call Surf cost: account BALANCE deltas recorded during the 2026-11-09 run (meta.credits_used is unreliable:
 *    it reports 5 for a keyed SQL call that costs 4, and 1 for a keyed label call that costs 4).
 *  - SERV / Dolphin per call: tokens from fixtures/models/*.json × documented per-1M prices.
 * --write appends the tables to artifacts/costs.md.
 */
import { appendFileSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const CREDIT = 0.006;
const PRICE = { cold: 0.15, cached: 0.05 };
const SERV_PER_M = { in: 1.0, out: 6.0 }; // gpt-5.4-mini, docs.openserv.ai/serv-reasoning/models
const DOLPHIN_PER_M = { in: 0.01, out: 0.07 }; // DeepSeek V4.1 Flash, dphn.ai/docs/dphn-api

/** Balance readings (surf me-credits) recorded in data/census-w90.log, data/labels-w90.log and this session's run notes. */
const BALANCE = {
  census_start: 324, // before the 90-day census (after the 365-day attempt)
  payees_done: 188, // after 800 payees (16 chunks + 1 killed call)
  funder_refused: 184, // after the refused funder pass
  labels_stopped: 72, // after 5 diagnostic + 22 run label calls (stopped at the floor)
};
const LABEL_CALLS = 5 + 22;

interface Call { prompt_tokens: number | null; completion_tokens: number | null }
const modelCost = (prefix: string, p: { in: number; out: number }) => {
  const files = readdirSync(join(ROOT, "fixtures", "models")).filter((f) => f.startsWith(prefix));
  const costs = files.flatMap((f) =>
    ((JSON.parse(readFileSync(join(ROOT, "fixtures", "models", f), "utf8")) as { calls: Call[] }).calls ?? [])
      .filter((c) => c.prompt_tokens !== null && c.completion_tokens !== null)
      .map((c) => (c.prompt_tokens! * p.in + c.completion_tokens! * p.out) / 1e6),
  );
  return { mean: costs.reduce((a, b) => a + b, 0) / Math.max(1, costs.length), n: costs.length };
};
const serv = modelCost("serv-", SERV_PER_M);
const dolphin = modelCost("dolphin-", DOLPHIN_PER_M);
const models = serv.mean + dolphin.mean;

const cp = JSON.parse(readFileSync(join(ROOT, "fixtures", "audit", "checkpoint-sample-census-w90.json"), "utf8")) as {
  chunk_costs?: { payees: number; credits: number | null }[];
  outbound_done?: string[];
  excluded?: string[];
};
const chunkCredits = (cp.chunk_costs ?? []).reduce((a, c) => a + (c.credits ?? 0), 0);
const chunkPayees = (cp.chunk_costs ?? []).reduce((a, c) => a + c.payees, 0);
const audited = (cp.outbound_done ?? []).filter((p) => !(cp.excluded ?? []).includes(p)).length;
const SQL = 4; // per keyed sync SQL call: 16 chunks × 2 calls = 128 credits = chunk_costs total
const LABEL = (BALANCE.funder_refused - BALANCE.labels_stopped) / LABEL_CALLS;
const payeePass = BALANCE.census_start - BALANCE.payees_done;

const fmt = (x: number, d = 4) => `$${x.toFixed(d)}`;
const pctm = (cost: number, price: number) => `${fmt(price - cost)} (${((1 - cost / price) * 100).toFixed(0)}%)`;
const cold = (sql: number, label: number) => (3 * sql + label) * CREDIT + models; // payee in + payee out + funder out + 1 label call
const L: string[] = [];
L.push(`## Pricing v2 (generated by \`npx tsx scripts/pricing.ts\`)`, ``);
L.push(`Inputs, all from account balance deltas on 2026-11-09: Surf $${CREDIT}/credit · SQL **${SQL}** credits/call (meta reports 5) · labels **${LABEL.toFixed(2)}** credits/call (${LABEL_CALLS} calls; meta reports 1) · SERV ${fmt(serv.mean, 5)}/call (n=${serv.n}) · Dolphin ${fmt(dolphin.mean, 6)}/call (n=${dolphin.n}).`, ``);
L.push(`| check type | what runs | cost | price | margin |`, `|---|---|---|---|---|`);
const cm = cold(SQL, 4);
const cc = cold(5, 4);
L.push(`| cold, measured (1 payee: 3 SQL × ${SQL} + 1 label call × 4) | 4 Surf calls + SERV + Dolphin | ${fmt(cm)} | ${fmt(PRICE.cold, 2)} | ${pctm(cm, PRICE.cold)} |`);
L.push(`| cold, conservative (3 SQL × 5 as meta reports + labels 4) | same | ${fmt(cc)} | ${fmt(PRICE.cold, 2)} | ${pctm(cc, PRICE.cold)} |`);
L.push(`| cached (snapshot hit) | SERV + Dolphin only | ${fmt(models)} | ${fmt(PRICE.cached, 2)} | ${pctm(models, PRICE.cached)} |`, ``);
L.push(`### Shrink table: Surf cost per payee as batch size grows (per-call billing)`, ``);
L.push(`| batch size | Surf credits / payee (3 SQL × ${SQL} + label calls × 4, ≤20 addresses/call, ≈2 addresses/payee) | Surf $ / payee | + models | total / check |`, `|---|---|---|---|---|`);
for (const b of [1, 10, 50, 300]) {
  const credits = (3 * SQL) / b + (Math.ceil((2 * b) / 20) * 4) / b;
  const usd = credits * CREDIT;
  L.push(`| ${b} | ${credits.toFixed(3)} | ${fmt(usd, 5)} | ${fmt(models, 5)} | ${fmt(usd + models, 5)} |`);
}
L.push(``, `### Census amortisation (90-day census, ${audited} payees, 2026-11-09)`, ``);
L.push(`| | credits | payees | $ / payee |`, `|---|---|---|---|`);
L.push(`| payee SQL chunks only (\`chunk_costs\`) | ${chunkCredits} | ${chunkPayees} | ${fmt((chunkCredits * CREDIT) / Math.max(1, chunkPayees), 5)} |`);
L.push(`| payee pass incl. billed killed call (balance ${BALANCE.census_start} → ${BALANCE.payees_done}) | ${payeePass} | ${audited} | ${fmt((payeePass * CREDIT) / Math.max(1, audited), 5)} |`);
L.push(`| + refused funder pass + partial labels (balance → ${BALANCE.labels_stopped}) | ${BALANCE.census_start - BALANCE.labels_stopped} | ${audited} | ${fmt(((BALANCE.census_start - BALANCE.labels_stopped) * CREDIT) / Math.max(1, audited), 5)} |`);
L.push(`| planning estimate (190 credits / 1,923 payees) | 190 | 1923 | ${fmt((190 * CREDIT) / 1923, 5)} |`, ``);
const md = L.join("\n") + "\n";
console.log(md);
if (process.argv.includes("--write")) appendFileSync(join(ROOT, "artifacts", "costs.md"), "\n" + md);
